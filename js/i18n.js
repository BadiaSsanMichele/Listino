let currentLang = localStorage.getItem('bsm-lang') || 'it';

function applyTranslations(lang) {
  const t = translations[lang];
  if (!t) return;
  document.body.classList.add('lang-transitioning');
  setTimeout(() => {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key] !== undefined) el.innerHTML = t[key];
    });
    document.documentElement.lang = lang;
    document.title = pageTitles[lang] || pageTitles.it;
    document.body.classList.remove('lang-transitioning');
  }, 180);
}

function initLangSwitch() {
  const buttons = document.querySelectorAll('.lang-btn');
  buttons.forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang');
      if (lang === currentLang) return;
      currentLang = lang;
      localStorage.setItem('bsm-lang', lang);
      buttons.forEach(b => b.classList.remove('lang-btn--active'));
      btn.classList.add('lang-btn--active');
      applyTranslations(lang);
    });
  });
  buttons.forEach(btn => {
    btn.classList.toggle('lang-btn--active', btn.getAttribute('data-lang') === currentLang);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  initLangSwitch();
  applyTranslations(currentLang);
});